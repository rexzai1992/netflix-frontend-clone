const COLLECTIONS = {
  featured: ["our-golden-night", "spring", "sprite-fright", "big-buck-bunny"],
  trending: ["sprite-fright", "charge", "coffee-run", "spring", "our-golden-night", "big-buck-bunny"],
  popular: ["big-buck-bunny", "sintel", "cosmos-laundromat", "caminandes-llamigos", "tears-of-steel"],
  movies: [], // filled below with every movie
  shows: [], // filled below with every show
};

const q = (value) => (value == null ? "NULL" : `'${String(value).replace(/'/g, "''")}'`);

const delivered = manifest.filter((entry) => !entry.skipped);
const bySlug = Object.fromEntries(delivered.map((entry) => [entry.slug, entry]));
const skipped = manifest.filter((entry) => entry.skipped);
for (const entry of skipped) console.warn(`skipped: ${entry.slug} — ${entry.skipped_reason || entry.reason || "?"}`);

const lines = [
  "-- Generated by scripts/generate-catalog-migration.mjs — licensed catalog.",
  "PRAGMA defer_foreign_keys = TRUE;",
  "",
  "-- Remove the copyrighted sample titles seeded by 0001.",
  `DELETE FROM content WHERE id IN (${REMOVED_SEED_IDS.map(q).join(", ")});`,
  "",
];

for (const entry of delivered) {
  const meta = METADATA[entry.slug];
  if (meta === null) {
    // our-golden-night: refresh media keys only.
    lines.push(
      "-- Our Golden Night gains its generated feature video and refreshed artwork.",
      `UPDATE content SET video_key = ${q(entry.video_key)}, poster_key = ${q(entry.poster_key)},`,
      `  backdrop_key = ${q(entry.backdrop_key)}, duration = ${q(entry.duration_label)},`,
      "  updated_at = CURRENT_TIMESTAMP",
      `  WHERE id = 'our-golden-night';`,
      "",
    );
    continue;
  }
  if (!meta) {
    console.warn(`No metadata for ${entry.slug}; skipping insert`);
    continue;
  }
  const duration = meta.duration || entry.duration_label;
  lines.push(
    `INSERT OR REPLACE INTO content (id, type, title, description, year, maturity_rating, duration, match_score, poster_key, backdrop_key, logo_key, video_key, featured, published, sort_order)`,
    `VALUES (${q(entry.slug)}, ${q(meta.type)}, ${q(entry.title)}, ${q(meta.description)}, ${entry.year}, ${q(meta.rating)}, ${q(duration)}, ${meta.match}, ${q(entry.poster_key)}, ${q(entry.backdrop_key)}, NULL, ${q(entry.video_key)}, 0, 1, ${meta.sort});`,
    "",
  );
}

for (const entry of delivered) {
  const meta = METADATA[entry.slug];
  if (!meta) continue;
  if (meta.type === "movie") COLLECTIONS.movies.push(entry.slug);
  if (meta.type === "show") COLLECTIONS.shows.push(entry.slug);
}
COLLECTIONS.movies.unshift("our-golden-night");

lines.push("-- Rebuild collection membership for the licensed catalog.");
for (const [collectionId, slugs] of Object.entries(COLLECTIONS)) {
  lines.push(`DELETE FROM collection_items WHERE collection_id = ${q(collectionId)};`);
  slugs
    .filter((slugName) => slugName === "our-golden-night" || bySlug[slugName])
    .forEach((slugName, index) => {
      lines.push(
        `INSERT OR REPLACE INTO collection_items (collection_id, content_id, sort_order) VALUES (${q(collectionId)}, ${q(slugName)}, ${(index + 1) * 10});`,
      );
    });
  lines.push("");
}

lines.push(
  "-- Footer attribution for the open movies.",
  `INSERT INTO site_settings (key, value, updated_at) VALUES ('attribution', ${q(
    delivered
      .filter((entry) => entry.slug !== "our-golden-night")
      .map((entry) => entry.attribution)
      .join(" · "),
  )}, CURRENT_TIMESTAMP)`,
  "ON CONFLICT(key) DO UPDATE SET value = excluded.value, updated_at = CURRENT_TIMESTAMP;",
  "",
);

await writeFile(new URL("../migrations/0004_licensed_catalog.sql", import.meta.url), lines.join("\n"));
